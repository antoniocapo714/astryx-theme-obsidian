/**
 * Writes themes/obsidian/darkDefaults.ts: Astryx's own dark-mode value for
 * every color token the theme does not set itself.
 *
 * Why: Obsidian is dark-only. A token the theme leaves unset falls back to
 * Astryx's default, which is a light-dark() pair — so on a machine set to light
 * mode, categorical badges, syntax colors and chart colors would turn light
 * while the rest of the theme stayed dark. Baking the dark half as a single
 * value makes every color one value, whatever the system preference.
 *
 * Rerun after upgrading @astryxdesign/core: `node scripts/bake-dark-defaults.mjs`.
 */
import { writeFileSync } from 'node:fs'
import { defineTheme } from '@astryxdesign/core/theme'
import { resolveThemeTokens } from '@astryxdesign/core/theme/tokens'

const probe = defineTheme({ name: 'obsidian-probe', tokens: {} })
const light = resolveThemeTokens(probe, { mode: 'light' })
const dark = resolveThemeTokens(probe, { mode: 'dark' })
const keys = Object.keys(dark)
  .filter((k) => k.startsWith('--color-') && light[k] !== dark[k])
  .sort()

for (const k of keys) {
  if (/light-dark\(/.test(dark[k])) throw new Error(`${k} still resolves to light-dark(): ${dark[k]}`)
}

const { version } = JSON.parse(
  await import('node:fs').then((fs) => fs.readFileSync(new URL('../node_modules/@astryxdesign/core/package.json', import.meta.url), 'utf8')),
)
const body = keys.map((k) => `  '${k}': '${dark[k]}',`).join('\n')
writeFileSync(
  new URL('../themes/obsidian/darkDefaults.ts', import.meta.url),
  `/**
 * GENERATED by scripts/bake-dark-defaults.mjs from @astryxdesign/core ${version}.
 * Do not edit by hand — rerun the script after upgrading Core.
 *
 * Astryx's dark value for every color token that differs between light and
 * dark mode. The theme spreads these first and overrides the ones it designs,
 * so no color is left to follow the system preference.
 */
export const darkDefaults = {
${body}
} as const
`,
)
console.log(`baked ${keys.length} color tokens from @astryxdesign/core ${version}`)
